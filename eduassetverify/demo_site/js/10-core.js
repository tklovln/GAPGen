function centroid(a) {
  let A = 0, cx = 0, cy = 0;
  const n = a.length / 2;
  for (let i = 0; i < n; i++) {
    const x0 = a[2 * i], y0 = a[2 * i + 1], x1 = a[(2 * i + 2) % a.length], y1 = a[(2 * i + 3) % a.length];
    const c = x0 * y1 - x1 * y0;
    A += c; cx += (x0 + x1) * c; cy += (y0 + y1) * c;
  }
  if (Math.abs(A) < 1e-6) { let sx = 0, sy = 0; for (let i = 0; i < n; i++) { sx += a[2 * i]; sy += a[2 * i + 1]; } return [sx / n, sy / n]; }
  return [cx / (3 * A), cy / (3 * A)];
}
