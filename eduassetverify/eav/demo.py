def _judge_v(it, bk, p=None):
    v = it["v"][bk]
    return sum((v[k] if p is None else v[k][p]).count("V") for k in "dcs")


def selections(its, N):
    """The assets the page shows before any browsing, each picked by a stated rule (index.html says
    the same):
      sim   the simulator's batch of 16: 6 violated assets that all three Claude judges accepted in
            pass 1 (the Fig. 1 asset first, then by item id), 4 correct assets that every method
            accepted in every pass under both backbones, 3 violated assets that every method rejected
            in every pass under both backbones, 2 assets that EduAssetVerify (Claude) sent to review
            in pass 1, and 1 correct asset that a Claude judge rejected in pass 1; the last four
            groups one per template and task in turn, by item id; shuffled with seed 0;
      game  every violated asset that some judge accepted in some pass, most accepted first;
      pairs the counterfactual pair per operator of the paper's appendix (fig_pairs)."""
    teaser = N["teaser"]["item_id"]
    by = {it["i"]: it for it in its}

    def spread(cands, n):
        """n candidates, one per task in turn and one per template, by item id."""
        cands = sorted(cands, key=lambda it: it["i"])
        out, used = [], set()
        tasks = ["fraction", "counting", "spatial"]
        while len(out) < n and cands:
            progressed = False
            for d in tasks:
                pick = next((it for it in cands if it["dm"] == d and it["t"] not in used), None)
                if pick and len(out) < n:
                    out.append(pick)
                    used.add(pick["t"])
                    cands.remove(pick)
                    progressed = True
            if not progressed:
                used.clear()
        return out

    allv = lambda it: all(it["v"][bk][k] == "VVV" for bk in "CG" for k in "dcse")
    alli = lambda it: all(it["v"][bk][k] == "III" for bk in "CG" for k in "dcse")
    slip = sorted((it for it in its if it["y"] == "I" and all(it["v"]["C"][k][0] == "V" for k in "dcs")),
                  key=lambda it: (it["i"] != teaser, it["i"]))[:6]
    good = spread([it for it in its if it["y"] == "V" and allv(it)], 4)
    caught = spread([it for it in its if it["y"] == "I" and alli(it)], 3)
    review = spread([it for it in its if it["v"]["C"]["e"][0] == "U" and it not in slip], 2)
    fr = spread([it for it in its if it["y"] == "V" and any(it["v"]["C"][k][0] == "I" for k in "dcs")
                 and it not in review], 1)
    sim = [it["i"] for it in slip + good + caught + review + fr]
    if len(sim) != 16 or len(set(sim)) != 16 or sim[0] != teaser:
        raise RuntimeError(f"simulator batch: {len(sim)} assets")
    rest = sim[1:]
    random.Random(0).shuffle(rest)
    sim = [sim[0]] + rest
    game = sorted((it for it in its if it["y"] == "I" and (_judge_v(it, "C") + _judge_v(it, "G")) > 0),
                  key=lambda it: (-(_judge_v(it, "C") + _judge_v(it, "G")), it["i"]))
    pairs = [[op, v["correct"], v["violated"]] for op, v in N["appendix"]["pairs"].items()]
    if any(p[1] not in by or p[2] not in by for p in pairs):
        raise RuntimeError("an appendix pair is not in the test split")
    return {"sim": sim, "game": [it["i"] for it in game], "pairs": pairs}


