def fonts_css() -> str:
    notes = "; ".join(f"{fam}: {c}" for fam, _, _, c in FONTS)
    out = [f"/* Web fonts, Latin subsets, licensed under the SIL Open Font License, Version 1.1 (see fonts/): {notes}. */"]
    for fam, file, wght, _ in FONTS:
        b64 = base64.b64encode((SITE / "fonts" / file).read_bytes()).decode()
        out.append(f'@font-face{{font-family:"{fam}";src:url(data:font/woff2;base64,{b64}) format("woff2");'
                   f"font-weight:{wght};font-style:normal;font-display:swap}}")
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--bench", default="data/bench_v1")
    ap.add_argument("--results", default="results/main")
    ap.add_argument("--numbers", default="results/paper/numbers.json")
    ap.add_argument("--out", default="results/demo")
    args = ap.parse_args()
    bench, out = pathlib.Path(args.bench), pathlib.Path(args.out)
    if out.exists():
        shutil.rmtree(out)
    (out / "media").mkdir(parents=True)
    (out / "fonts").mkdir()
    man = MX.load_manifest(bench)
    recs = {(k, b): MX.load_results(pathlib.Path(args.results) / f"{k}__{b}.jsonl") for k, _ in METHODS for b in BACKBONES}
    by = index(recs)
    N = json.loads(pathlib.Path(args.numbers).read_text())
    its, media, images = items(man, by, bench)
    sel = selections(its, N)
    res = results(N)
    for b, (k, _) in BACKBONES.items():                     # the item-level verdicts add up to numbers.json
        for kind, short in METHODS:
            got = sum(it["v"][k][short].count("V") for it in its if it["y"] == "I")
            if got != res["fa"][k][kind]:
                raise RuntimeError(f"false acceptances of {kind} under {b}: items {got}, numbers.json {res['fa'][k][kind]}")
    wt = walkthrough(N, man, by, bench, media)
    featured = {iid for iid in sel["sim"] + sel["game"] + [x for p in sel["pairs"] for x in p[1:]]}
    hero = [wt["item"], next(it["p"] for it in its if it["i"] == wt["item"])]
    crops = {iid: list(PP.circle_crop(json.loads((bench / "specs" / f"{iid}.json").read_text()), pad=18)) for iid in hero}
    data = {"backbones": [[k, name] for k, name in BACKBONES.values()],
            "conditions": [list(x) for x in PP.SPLIT_NAMES],
            "operators": [[op, name, task] for task, rows in PP.OPERATOR_ROWS for op, name in rows],
            "templates": PP.TEMPLATE_NAMES, "sel": sel, "hero": {iid: images[iid] for iid in hero}, "crops": crops,
            "items": its, "walkthrough": wt, "results": res}
    (out / "data.js").write_text(HEAD + "window.EAV = " + json.dumps(data, separators=(",", ":")) + ";\n")
    tmpl = {it["i"]: it["t"] for it in its}
    (out / "media" / "featured.js").write_text(
        HEAD + 'EAV_MEDIA("featured",' + json.dumps({iid: {"im": images[iid], "j": media[tmpl[iid]][iid]["j"]} for iid in sorted(featured)},
                                                     separators=(",", ":")) + ");\n")
    for t, mp in sorted(media.items()):
        for iid in mp:
            mp[iid]["im"] = images[iid]
        (out / "media" / f"{t}.js").write_text(HEAD + f"EAV_MEDIA({json.dumps(t)}," + json.dumps(mp, separators=(",", ":")) + ");\n")
    (out / "style.css").write_text(fonts_css() + (SITE / "style.css").read_text())
    parts = sorted((SITE / "js").glob("*.js"))
    (out / "app.js").write_text(HEAD.replace("*/", "(joined from demo_site/js/) */") + '(function () {\n"use strict";\n'
                                + "\n".join(f.read_text() for f in parts) + "\n})();\n")
    shutil.copy(SITE / "index.html", out / "index.html")
    for fam, _, _, _ in FONTS:
        shutil.copy(SITE / "fonts" / f"{fam}-OFL.txt", out / "fonts" / f"{fam}-OFL.txt")
    (out / ".nojekyll").write_text("")
    # anonymity and portability: no page file may name the author or contain an absolute URL
    bad = [(str(p.relative_to(out)), mt.group(0)) for p in out.rglob("*") if p.suffix in (".html", ".css", ".js")
           for mt in [FORBIDDEN.search(p.read_text())] if mt]
    if bad:
        raise RuntimeError(f"forbidden strings in the site: {bad}")
    files = [p for p in out.rglob("*") if p.is_file()]
    sizes = {str(p.relative_to(out)): p.stat().st_size for p in files}
    big = max((k for k in sizes if k.startswith("media/") and k != "media/featured.js"), key=sizes.get)
    print(f"wrote {len(files)} files, {sum(sizes.values()) / 1e6:.1f} MB to {out}: data.js {sizes['data.js'] / 1e6:.2f} MB, "
          f"featured {sizes['media/featured.js'] / 1e6:.2f} MB ({len(featured)} images), style.css {sizes['style.css'] / 1e3:.0f} kB, "
          f"largest template file {big} {sizes[big] / 1e6:.2f} MB")


if __name__ == "__main__":
    main()
