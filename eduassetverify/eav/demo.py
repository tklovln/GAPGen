def results(N):
    """Every summary number the page shows, read from numbers.json: [value, label] pairs, where the
    label is formatted as the paper prints it. Backbones are keyed C and G."""
    bk = {b: BACKBONES[b][0] for b in BACKBONES}
    order = list(PP.BACKBONES)                      # the paper's order: Gemini, then Claude
    gem, cla = order
    main = {}
    for key, _ in PP.MAIN_ROWS:
        for b in order:
            s = N["main"]["clip"] if key == "clip" else N["main"][f"{key}__{b}"]
            main.setdefault(key, {})[bk[b]] = {c: _val(s[c]) for c in PP.MAIN_COLS}
    ex = N["extras"]
    den = ex["violated_evals_by_operator"]
    kinds = ("direct", "cot", "structured", "eav")
    ops = []
    for task, rows in PP.OPERATOR_ROWS:
        for op, name in rows:
            ops.append([op, name, task, {bk[b]: {k: [*_val(ex[f"fa_by_operator__{k}__{b}"].get(op, 0) / den[op]),
                                                     ex[f"fa_by_operator__{k}__{b}"].get(op, 0), den[op]] for k in kinds}
                                         for b in order}])
    combined = sum(v for op, v in den.items() if "+" in op)
    two = {bk[b]: {k: [*_val(sum(v for op, v in ex[f"fa_by_operator__{k}__{b}"].items() if "+" in op) / combined),
                       sum(v for op, v in ex[f"fa_by_operator__{k}__{b}"].items() if "+" in op), combined] for k in kinds}
           for b in order}
    ops.append(["two_operators", "Two operators", "Combined", two])
    domain = {bk[b]: {k: {d: _val(N["domain"][f"{k}__{b}"][d]["far"]) for d in ("fraction", "counting", "spatial")}
                      for k in ("direct", "cot", "structured", "rule_only", "eav")} for b in order}
    conds = [[sp, name, {bk[b]: {k: _val(N["split"][f"{k}__{b}"][sp]["pair_accuracy"]) for k in ("direct", "cot", "structured", "eav")}
                         for b in order}] for sp, name in PP.SPLIT_NAMES]
    conds.append(["invariance", "Style invariance", {bk[b]: {k: _val(N["invariance"][f"{k}__{b}"]) for k in ("direct", "cot", "structured", "eav")}
                                                    for b in order}])
    abl = [[k, name, {bk[b]: {c: _val(N["main"][f"{k}__{b}"][c]) for c in ("far", "frr", "abstention")} for b in order}]
           for k, name in [("eav", "Full EduAssetVerify"), ("vlmrules", "Without rule engine"),
                           ("abl_no_measure", "Without measurement"), ("abl_no_semantic", "Without semantic verifier"),
                           ("abl_no_abstain", "Without abstention")]]
    cost = {bk[b]: {k: {"usd": round(N["cost"][f"{k}__{b}"]["usd_1k"], 2), "calls": round(N["cost"][f"{k}__{b}"]["calls"], 2),
                        "tin": round(N["cost"][f"{k}__{b}"]["tin"]), "tout": round(N["cost"][f"{k}__{b}"]["tout"]),
                        "lat": round(N["cost"][f"{k}__{b}"]["latency"], 1)}
                    for k in ("direct", "cot", "structured", "rule_only", "eav")} for b in order}
    loc = {bk[b]: {"type": _val(N["main"][f"eav__{b}"]["violation_type_accuracy"]),
                   "witness": _val(N["main"][f"eav__{b}"]["localization_accuracy"])} for b in order}
    parse = {bk[b]: {"exact": _val(N["parse"][b]["extraction"]["exact"]), "far": _val(N["parse"][b]["pipeline"]["far"]),
                     "detected": _val(N["parse"][b]["consistency"]["detected"])} for b in order}
    fa = {bk[b]: {k: ex[f"fa_total__{k}__{b}"] for k in ("direct", "cot", "structured", "rule_only", "eav")} for b in order}
    ratio = {bk[b]: [round(cost[bk[b]]["eav"]["usd"] / max(cost[bk[b]][k]["usd"] for k in ("direct", "cot", "structured")), 1),
                     round(cost[bk[b]]["eav"]["usd"] / min(cost[bk[b]][k]["usd"] for k in ("direct", "cot", "structured")), 1)]
             for b in order}
    acc = {(k, b): N["main"][f"{k}__{b}"]["accuracy"][0] for k in ("direct", "cot", "structured", "rule_only", "eav") for b in order}
    judges = ("direct", "cot", "structured")
    # the claims of index.html, asserted on the numbers
    claims = {
        "EduAssetVerify accepted no violated test asset under either backbone": all(fa[bk[b]]["eav"] == 0 for b in order),
        "under Gemini every judge is more accurate than EduAssetVerify": all(acc[(k, gem)] > acc[("eav", gem)] for k in judges),
        "under Claude EduAssetVerify is more accurate than every judge": all(acc[("eav", cla)] > acc[(k, cla)] for k in judges),
        "the rule-only validator accepts no violated asset": all(N["main"][f"rule_only__{b}"]["far"][0] == 0 for b in order),
        "the rule-only validator is more accurate than the full method": all(acc[("rule_only", b)] > acc[("eav", b)] for b in order),
        "without the semantic verifier, FAR stays zero and FRR moves by under half a point (down under Gemini, up under Claude)":
            all(N["main"][f"abl_no_semantic__{b}"]["far"][0] == 0 and abs(N["main"][f"abl_no_semantic__{b}"]["frr"][0]
                                                                          - N["main"][f"eav__{b}"]["frr"][0]) < 0.005 for b in order)
            and N["main"][f"abl_no_semantic__{gem}"]["frr"][0] < N["main"][f"eav__{gem}"]["frr"][0]
            and N["main"][f"abl_no_semantic__{cla}"]["frr"][0] > N["main"][f"eav__{cla}"]["frr"][0],
        "abstention prevents no false acceptance": all(N["main"][f"abl_no_abstain__{b}"]["far"][0] == N["main"][f"eav__{b}"]["far"][0] for b in order),
        "without abstention, false rejections rise": all(N["main"][f"abl_no_abstain__{b}"]["frr"][0] > N["main"][f"eav__{b}"]["frr"][0] for b in order),
        "EduAssetVerify costs four to ten times a judge": all(4 <= r[0] and r[1] < 10 for r in ratio.values()),
    }
    wrong = [c for c, ok in claims.items() if not ok]
    if wrong:
        raise RuntimeError(f"the text of the page no longer holds: {wrong}")
    return {"order": [bk[b] for b in order], "main": main, "fa": fa, "ops": ops, "domain": domain, "conditions": conds,
            "ablation": abl, "cost": cost, "cost_ratio": ratio, "loc": loc, "parse": parse,
            "abstention": {bk[b]: _pct(N["main"][f"eav__{b}"]["abstention"]) for b in order},
            "n_violated_evals": 3 * N["n_violated_test"], "n_test": N["n_test"],
            "max_sd": round(100 * N["max_sd_main_table"], 1), "errors": N["appendix"]["errors"],
            "zones": {"equal_area": list(Config().equal_area), "symmetry": list(Config().symmetry), "tau": Config().tau,
                      "area_margin": Config().area_margin, "iou_margin": Config().iou_margin}}


