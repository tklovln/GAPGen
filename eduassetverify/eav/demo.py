# --------------------------------------------------------------------------- small helpers

def _flat(o) -> bool:
    """True if a JSON value reads well on one line: scalars, or containers of scalars and of flat dicts."""
    def scalar(v):
        return not isinstance(v, (dict, list))
    if isinstance(o, dict):
        return all(scalar(v) or (isinstance(v, dict) and all(scalar(x) for x in v.values())) for v in o.values())
    if isinstance(o, list):
        return all(scalar(v) for v in o)
    return True


def _pretty(o, ind: int = 0) -> str:
    """A model answer, pretty-printed with one line per part or constraint."""
    pad = "  " * ind
    if _flat(o):
        return json.dumps(o, separators=(", ", ": "), ensure_ascii=False)
    if isinstance(o, dict):
        rows = [f"{pad}  {json.dumps(k)}: {_pretty(v, ind + 1)}" for k, v in o.items()]
        return "{\n" + ",\n".join(rows) + "\n" + pad + "}"
    rows = [pad + "  " + _pretty(v, ind + 1) for v in o]
    return "[\n" + ",\n".join(rows) + "\n" + pad + "]"


def _vlm(model):
    return make(model, temperature=0.7, thinking_budget=1024 if model.startswith("gemini") else None)


def _cached(vlm, prompt, images, sample):
    r = vlm.ask(prompt, images, sample=sample, allow_network=False)
    if r.get("error"):
        raise RuntimeError(f"not in the response cache: {vlm.model} {sample}")
    return r["text"]


def _fmt(v):
    if v is None:
        return ""
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, float):
        return f"{v:.2f}"
    if isinstance(v, (list, tuple)):
        if v and all(isinstance(x, str) for x in v):
            return ", ".join(f"{k} \u00d7{n}" if n > 1 else k for k, n in Counter(v).most_common())
        return ", ".join(_fmt(x) for x in v)
    return str(v)


def _box(b):
    return None if not b else [round(float(v), 1) for v in b]


def _ibox(b):
    return None if not b else [int(round(float(v))) for v in b]


def _webp(rgb: np.ndarray) -> str:
    """A lossless WebP data URI that decodes to exactly these pixels (and carries no metadata)."""
    buf = io.BytesIO()
    Image.fromarray(rgb).save(buf, "WEBP", lossless=True, quality=80, method=4)
    raw = buf.getvalue()
    if not np.array_equal(np.asarray(Image.open(io.BytesIO(raw)).convert("RGB")), rgb):
        raise RuntimeError("lossless WebP does not reproduce the pixels")
    if raw[:4] != b"RIFF" or raw[8:16] != b"WEBPVP8L":
        raise RuntimeError("unexpected WebP container (metadata chunks?)")
    return "data:image/webp;base64," + base64.b64encode(raw).decode()


def _rgb(bench, m) -> np.ndarray:
    return np.asarray(Image.open(bench / m["image"]).convert("RGB"))


def _verdict(js) -> str:
    """The verdict of a judge's answer, parsed as eav.methods.judges.run_judge does."""
    v = str(js.get("verdict", "")).strip().upper() if js else ""
    return v if v in ("VALID", "INVALID") else "UNPARSABLE"


def _check(js, by, kind, b, iid):
    rec = by[(kind, b)][iid][0]["verdict"]
    if _verdict(js) != rec:
        raise RuntimeError(f"cached {kind} answer of {b} on {iid} says {_verdict(js)}, the record says {rec}")


def _pct(ms, sd=False):
    """paper.pct for values read back from numbers.json, where (mean, sd) pairs are lists."""
    return PP.pct(tuple(ms) if isinstance(ms, list) else ms, sd=sd)


def _val(ms):
    """[mean, label] of a (mean, sd) pair or a plain rate: the label as the paper prints it."""
    mean = ms[0] if isinstance(ms, (list, tuple)) else ms
    return [round(float(mean), 5), _pct(ms)]


# --------------------------------------------------------------------------- evidence and measurement

def _ev(ev) -> dict | None:
    """One evidence graph, compact: shapes with parts, objects, texts, lines (512-pixel frame)."""
    if not ev["ok"]:
        return None
    out = {}
    if ev["shapes"]:
        out["s"] = [[s["shape"], _ibox(s["box"]), [[_ibox(p["box"]), int(p["colored"])] for p in s["parts"]]] for s in ev["shapes"]]
    if ev["objects"]:
        out["o"] = [[o["category"], _ibox(o["box"]), o["direction"]] for o in ev["objects"]]
    if ev["texts"]:
        out["t"] = [[t["text"], _ibox(t["box"])] for t in ev["texts"]]
    if ev["lines"]:
        out["l"] = [[ln["style"], ln["orientation"], None if ln["position"] is None else round(ln["position"], 1)]
                    for ln in ev["lines"]]
    return out


def _sem(s) -> dict | None:
    if not s:
        return None
    out = {}
    if s.get("text") is not None:
        out["x"] = s["text"]
        out["b"] = _ibox(s.get("box"))
    if s.get("categories") is not None:
        out["k"] = s["categories"]
    return out or None


def _readings(rec) -> list:
    """Per constraint of the report: [name, status, q, witness, [[status, value, weight, conflict, source]]]."""
    return [[d["name"], d["status"], round(d["q"], 2), _box(d["witness"]),
             [[r["status"], _fmt(r["value"]), round(r["weight"], 2), int(r["conflict"]), r["source"]] for r in d["readings"]]]
            for d in rec["report"]]


def _contour(mask: np.ndarray, ox: int, oy: int) -> list[int]:
    cs, _ = cv2.findContours(np.ascontiguousarray(mask.astype(np.uint8)), cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    c = max(cs, key=cv2.contourArea)
    pts = cv2.approxPolyDP(c, 0.7, True)[:, 0, :]
    return [int(v) for v in (pts + np.array([ox, oy])).flatten()]


def _same(rd, value) -> bool:
    if isinstance(value, float):
        return isinstance(rd["value"], (int, float)) and abs(rd["value"] - value) < 1e-9
    return rd["value"] == value


def measured(m, rec, rgb) -> dict | None:
    """What eav.measure found on one record: recomputed exactly as eav.rules.check calls it (same
    boxes, same caching) and checked against the values the report recorded."""
    names = {c["name"] for c in m["constraints"]}
    report = {d["name"]: d for d in rec["report"]}
    oks = [i for i, ev in enumerate(rec["readings"]) if ev["ok"]]
    if not oks:
        return None
    frac = [n for n in ("part_count", "colored_part_count", "equal_area") if n in report]
    if frac:
        for i in oks:
            shape = _main_shape(rec["readings"][i])
            if shape is None:
                continue
            part = M.partition(rgb, shape["box"], masks=True)
            got = {"part_count": part.get("n"), "colored_part_count": part.get("colored"), "equal_area": part.get("deviation")}
            for n in frac:
                rd = report[n]["readings"][i]
                if part["ok"] != (rd["source"] == "measured") or (part["ok"] and not _same(rd, got[n])):
                    raise RuntimeError(f"{m['item_id']}: recomputed partition differs from the record ({n}, reading {i})")
            if not part["ok"]:
                continue
            ox, oy = part["origin"]
            areas = np.array([p["area"] for p in part["parts"]], float)
            return {"k": "part", "r": i, "n": part["n"], "c": part["colored"], "d": round(part["deviation"], 4),
                    "w": _ibox(part["worst"]),
                    "p": [[_contour(p["mask"], ox, oy), round(float(a / areas.mean()), 3), int(p["colored"])]
                          for p, a in zip(part["parts"], areas)]}
        return None
    if "object_count" in report:
        line = M.vertical_line(rgb)
        bl = M.count_blobs(rgb, line["x"] if line["ok"] else None)
        rd = report["object_count"]["readings"][oks[0]]
        if bl["ok"] != (rd["source"] == "measured") or (bl["ok"] and not _same(rd, bl["n"])):
            raise RuntimeError(f"{m['item_id']}: recomputed object count differs from the record")
        return {"k": "blobs", "n": bl["n"], "b": [_ibox(x["bbox"]) for x in bl["blobs"]]} if bl["ok"] else None
    if "mirror_symmetric" in report:
        ev = rec["readings"][oks[0]]
        dashed = [ln for ln in ev["lines"] if ln["orientation"] == "vertical" and ln["position"] is not None]
        sym = M.symmetry(rgb, dashed[0]["position"] if dashed else None)
        rd = report["mirror_symmetric"]["readings"][oks[0]]
        if sym["ok"] != (rd["source"] == "measured") or (sym["ok"] and not _same(rd, sym["iou"])):
            raise RuntimeError(f"{m['item_id']}: recomputed symmetry differs from the record")
        return {"k": "sym", "iou": round(sym["iou"], 4), "x": round(sym["axis"], 1), "w": _ibox(sym["worst"])} if sym["ok"] else None
    return None


