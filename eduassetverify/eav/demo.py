def walkthrough(N, man, by, bench, media):
    """The Fig. 1 asset through every module (Claude Sonnet 5, pass 1): the parser's answer and
    the judges' answers from the response cache, the three evidence graphs and the report from the
    run record, the measurement overlay (checked against numbers.json's overview), and Fig. 2's values."""
    ov, te = N["overview"], N["teaser"]
    iid = ov["item_id"]
    m = man[iid]
    b = ov["backbone"]
    bk = BACKBONES[b][0]
    png = (bench / m["image"]).read_bytes()
    claude = _vlm(b)
    parse_raw = parse_json(_cached(claude, PA.prompt(m["objective"]), [], "parse-p0"))
    frame = P.frame_for(b)
    g_prompt = P.grounding("partition", None, frame)
    g_raw = parse_json(_cached(claude, g_prompt, [png], "p0-g0"))
    judges = {}
    for bb, (k, _) in BACKBONES.items():
        v = _vlm(bb)
        judges[k] = {kind: parse_json(_cached(v, fn(m["objective"], m["constraints"]), [png], "p0"))
                     for kind, fn in (("direct", P.judge_direct), ("cot", P.judge_cot), ("structured", P.judge_structured))}
        for kind, js in judges[k].items():
            _check(js, by, kind, bb, iid)
    ms = media[m["template"]][iid]["ms"][bk]
    ratios = sorted(p[1] for p in ms["p"])
    if ms["n"] != ov["measurement"]["regions"] or abs(ms["d"] - ov["measurement"]["deviation"]) > 1e-4 \
            or any(abs(a - c) > 1e-3 for a, c in zip(ratios, sorted(ov["measurement"]["ratios"]))):
        raise RuntimeError("walkthrough measurement differs from numbers.json (overview)")
    spec = json.loads((bench / "specs" / f"{iid}.json").read_text())["scene"]
    meas = ov["measurement"]
    return {"item": iid, "objective": m["objective"], "backbone": BACKBONES[b][1], "bk": bk,
            "spec": {"sizes": [round(v, 5) for v in spec["sizes"]], "colored": [int(c) for c in spec["colored"]],
                     "start": round(spec["geom"]["start"], 2)},
            "witness": [int(v) for v in ov["witness"]],
            "parser_answer": _pretty(parse_raw),
            "parser_same_everywhere": ov["same_constraints_every_backbone_and_pass"],
            "constraints": ov["constraints"],
            "grounding_prompt": g_prompt, "grounding_answer": _pretty(g_raw),
            "readings": media[m["template"]][iid]["ev"][bk], "report": media[m["template"]][iid]["rd"][bk],
            "measured": ms,
            "measurement": {"regions": meas["regions"], "colored": meas["colored"], "deviation": round(meas["deviation"], 2),
                            "largest": round(max(meas["ratios"]), 2), "smallest": round(min(meas["ratios"]), 2)},
            "rules": [[r["name"], _fmt(r["value"]), r["status"], round(r["q"], 2)] for r in ov["rules"]],
            "agree": ov["readings_agree"], "verdict": ov["verdict"], "same_verdict_gemini": ov["same_verdict_under_gemini"],
            "judges": judges, "spec_ratio": round(te["largest_part_ratio_spec"], 3)}


